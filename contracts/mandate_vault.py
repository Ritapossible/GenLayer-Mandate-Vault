"""MandateVault - a spending mandate an autonomous agent cannot argue with.

The problem: agents are being handed payment authority, and that authority is
always written in prose ("buy compute for training runs and datasets, nothing
else") while the enforcement is always a hard cap. A cap cannot tell a GPU lease
from a gift card. Closing that gap needs a judgment about *meaning* at the
moment of spending, and there is nowhere trustworthy to put it: an oracle cannot
read intent, and off-chain review means trusting the operator the mandate exists
to constrain.

The split that makes it safe:

  the code judges quantity  - per-transaction cap, rolling period cap,
                              denylist, allowlist. Deterministic, no LLM.
  the model judges kind     - "does this purpose fall under clause N?"
                              One LLM call, and only if the numbers cleared.

Every request is screened deterministically first, and most settle there. Only a
request that passes every limit and still needs a judgment about purpose reaches
a model, so nondet cost is at most one LLM call per spend regardless of how
elaborate the mandate is.

Fail closed. A denial costs a round trip and an owner override; a wrongful
approval costs money that does not come back. Every ambiguous, malformed, or
hostile model response resolves to a denial, and `canonicalize_verdict` is total.

Consensus design. Validators re-run the whole leader computation and compare
field by field: `decision` and `clause_id` exactly, `confidence` within
tolerance and only for approvals. Nothing is trusted from the leader beyond the
values being compared, per GenLayer's rule that the leader's result is never
trusted input. Confidence is deliberately not compared on denials -- the number
changes no outcome there, so comparing it would manufacture disagreement without
buying safety.

The comparison happens *after* canonicalization, never before. The leader's
calldata is admitted only if `canonicalize_verdict` leaves it unchanged
(`canonical_leader_verdict`), which is the same coercion the agreed result
passes through on its way to storage. Compare earlier than that and the
tolerance spans the `min_confidence` threshold: 74 and 94 are both within 20 of
an independently computed 94, but one stores a denial and the other an approval.
The tolerance absorbs spread among approvals; it must not carry agreement across
the line that decides whether the spend happens.

Injection containment. The model is asked only whether a purpose fits a clause.
It never sees an amount, a balance, a cap, or a party name, so memo text has no
lever even if the model obeys it -- nothing in the prompt connects an answer to
money. `clause_id` is coerced against the mandate's own ids, so a request cannot
cite authority that does not exist. The worst a hostile memo achieves is one
miscategorization inside limits that were already fixed deterministically.

Note this is defense-in-depth, not a substitute for greyboxing: an injection
every validator's model obeys would reach consensus. Bounding the blast radius
is the durable property, not preventing agreement.

Layout. This file is the whole contract and the only one in `contracts/`.
GenLayer deploys a single file, so the deterministic engine
(`src/mandate_core.py`) and the prompt builder (`src/mandate_prompts.py`) are
inlined below between INLINE markers rather than imported. Those two modules
remain the source of truth and are what the test suite exercises;
`tools/build_contract.py` regenerates the marked regions and
`tests/test_contract_sync.py` fails if this file falls behind them.

The library modules live outside `contracts/` deliberately. They declare no
`gl.Contract` and are never deployed, so keeping them out of the contract
directory leaves a validator exactly one candidate to check.
"""

