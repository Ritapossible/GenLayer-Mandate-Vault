def _parse_address(raw: object, field: str) -> Address:
    """Accept an address as either a decoded `Address` or its hex text.

    Both spellings arrive in practice, and refusing the first made every
    address-taking method unreachable from the standard tooling. GenLayer
    calldata has a **native address type**, and `genlayer` CLI emits it by
    default: a bare 40-hex-character argument is auto-detected and encoded as
    `addr#...`, so the runner hands this function an `Address` object, not a
    `str`. A `str` guard alone therefore rejected the only form the CLI
    produces -- `request_spend` rolled back with "payee must be a string"
    against calldata that named a perfectly good address.

    That failure is invisible to a test suite that passes hex strings, which is
    what every test did until the decoded-address cases in
    `test_contract_runtime.py` were added. It took a live transaction to
    surface, and the receipt named it exactly.

    `Address(...)` raises its own exception on malformed input. Left unguarded
    that surfaces as a runtime fault rather than a rejected transaction, which
    reads to a caller as "the contract is broken" instead of "that address is
    wrong". Bad input from a caller is an expected condition, so it is reported
    as one.
    """
    if isinstance(raw, Address):
        return raw
    if not isinstance(raw, str):
        raise gl.vm.UserError(
            f"{ERROR_EXPECTED} {field} must be an address or a hex string"
        )
    try:
        return Address(raw)
    except Exception:
        raise gl.vm.UserError(f"{ERROR_EXPECTED} {field} is not a valid address") from None


# A parameter annotation is documentation, not enforcement. The runner resolves
# the method and calls it with the decoded calldata as-is --
# `meth2call(contract_instance, *cd["args"], **cd["kwargs"])` -- and neither
# `@gl.public.write` nor `@gl.public.view` wraps the function; both only set
# attributes on it. So an `amount: int` parameter genuinely arrives as whatever
# the caller encoded, and calldata decodes to
# `None | int | str | bytes | list | dict | Address`.
#
# `Address` belongs on that list and its absence was a real defect, not a
# documentation slip: it is why `_parse_address` used to refuse the CLI's own
# encoding. See that function.
#
# Every such value has to be refused at the boundary, before any arithmetic
# touches it. `int("abc")` raises `ValueError` and `None < 0` raises
# `TypeError`, and either escapes as an unclassified VM error -- the one thing
# the error-class protocol exists to prevent, because validators have no rule
# for comparing a failure that carries no prefix.


def _require_int(raw: object, field: str) -> int:
    """Coerce a calldata field to a real int, failing as a classified error.

    A bool is refused rather than widened, for the reason it is refused
    throughout the verdict layer: `True == 1` in Python, so accepting one would
    let `request_spend(payee, True, memo)` read as a one-base-unit spend.
    """
    if isinstance(raw, bool) or not isinstance(raw, int):
        raise gl.vm.UserError(f"{ERROR_EXPECTED} {field} must be an integer")
    return raw


def _require_u256(raw: object, field: str) -> int:
    """Coerce a calldata field to an int a `u256` slot can actually hold.

    Only the upper bound is checked. Every caller either feeds the result to
    `Limits.validate()`, which names the specific bound a negative missed, or --
    in `request_spend`'s case -- wants a negative amount recorded as a denial
    rather than raised. Rejecting negatives here would take both of those away
    and replace them with a worse message.
    """
    value = _require_int(raw, field)
    if value > U256_MAX:
        raise gl.vm.UserError(f"{ERROR_EXPECTED} {field} exceeds u256 range")
    return value


def _require_bool(raw: object, field: str) -> bool:
    """Coerce a calldata field to a real bool, failing as a classified error.

    Stricter than truthiness on purpose, and this one is an authorization bug
    rather than a crash. `BoolDesc.set` writes `1 if val else 0`, so it accepts
    any object and reads its truthiness -- and every non-empty string is truthy.
    Without this guard `set_agent(addr, "false")` would *grant* that address
    spending authority, and `set_denylist(payee, "")` would silently unblock a
    payee the owner meant to block.
    """
    if not isinstance(raw, bool):
        raise gl.vm.UserError(f"{ERROR_EXPECTED} {field} must be a boolean")
    return raw


@allow_storage
@dataclass
class Spend:
    requester: Address
    payee: Address
    amount: u256
    memo: str
    outcome: str  # "approved" | "denied"
    reason: str  # see REASONS
    clause_id: u256  # meaningful only when `cited`
    cited: bool
    confidence: u256
    at: u256  # unix seconds, from consensus-provided block time


class MandateVault(gl.Contract):
    owner: Address
    clauses: DynArray[str]
    revoked: DynArray[bool]
    agents: TreeMap[str, bool]
    allowlist: TreeMap[str, bool]
    denylist: TreeMap[str, bool]
    spends: DynArray[Spend]
    per_tx_cap: u256
    period_cap: u256
    period_seconds: u256
    auto_approve_under: u256
    min_confidence: u256
    confidence_tol: u256

    def __init__(
        self,
        clauses: list[str],
        per_tx_cap: int,
        period_cap: int,
        period_seconds: int = 604800,
        auto_approve_under: int = 0,
        min_confidence: int = 75,
        confidence_tol: int = 20,
    ):
        # The two ways a mandate arrives unusable are separate rejections
        # because they have different remedies, and a single message for both
        # sent at least one deploy chasing the wrong one.
        #
        # `[]` is a deploy that supplied no clauses -- an empty Studio form.
        #
        # A non-list is a deploy whose clause array never survived the shell.
        # `--args` is JSON-decoded per value by the CLI, so the array has to
        # reach it with its double quotes intact; a shell that eats them leaves
        # `["a","b"]` as the string `[a,b]`, which fails `JSON.parse` and is
        # forwarded as a scalar. Naming the arrival type says so, where "at
        # least one clause" reads as "you passed none" to someone looking at a
        # command that plainly passes two.
        if not isinstance(clauses, list):
            raise gl.vm.UserError(
                f"{ERROR_EXPECTED} clauses must be an array of strings, got "
                f"{type(clauses).__name__}"
            )
        if not clauses:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} mandate must have at least one clause")
        for text in clauses:
            if not isinstance(text, str) or not text.strip():
                raise gl.vm.UserError(f"{ERROR_EXPECTED} clause text must be non-empty")
            if len(text) > MAX_CLAUSE_CHARS:
                raise gl.vm.UserError(f"{ERROR_EXPECTED} clause too long")

        # Validate the numbers through the same path the write path uses, so a
        # misconfigured deploy fails at construction instead of at first spend.
        # `validate()` speaks ValueError because it is runtime-independent; the
        # contract boundary restates it as a classified error.
        #
        # The type and range checks come first because `validate()` cannot do
        # them: it compares (`per_tx_cap < 1`), and comparing a str to an int
        # raises `TypeError`, which is not what the `except` below catches. The
        # upper bound is checked for the same reason the fields are written as
        # `u256` -- `validate()` has no opinion about width, so a cap of `2**300`
        # would clear it and then fault inside `u256()` further down.
        per_tx_cap = _require_u256(per_tx_cap, "per_tx_cap")
        period_cap = _require_u256(period_cap, "period_cap")
        period_seconds = _require_u256(period_seconds, "period_seconds")
        auto_approve_under = _require_u256(auto_approve_under, "auto_approve_under")
        min_confidence = _require_u256(min_confidence, "min_confidence")
        confidence_tol = _require_u256(confidence_tol, "confidence_tol")

        try:
            Limits(
                per_tx_cap=per_tx_cap,
                period_cap=period_cap,
                period_seconds=period_seconds,
                auto_approve_under=auto_approve_under,
                min_confidence=min_confidence,
                confidence_tol=confidence_tol,
            ).validate()
        except ValueError as e:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} {e}") from None

        self.owner = gl.message.sender_address
        for text in clauses:
            self.clauses.append(text)
            self.revoked.append(False)

        self.per_tx_cap = u256(per_tx_cap)
        self.period_cap = u256(period_cap)
        self.period_seconds = u256(period_seconds)
        self.auto_approve_under = u256(auto_approve_under)
        self.min_confidence = u256(min_confidence)
        self.confidence_tol = u256(confidence_tol)

    # --- config plumbing ---

    def _limits(self) -> Limits:
        return Limits(
            per_tx_cap=int(self.per_tx_cap),
            period_cap=int(self.period_cap),
            period_seconds=int(self.period_seconds),
            auto_approve_under=int(self.auto_approve_under),
            min_confidence=int(self.min_confidence),
            confidence_tol=int(self.confidence_tol),
        )

    def _active_clauses(self) -> list[tuple[int, str]]:
        """Live clauses as (id, text), keeping original ids.

        Revocation blanks a clause rather than removing it, so ids stay stable:
        a stored spend citing clause 3 still means clause 3 a year later, and
        history remains auditable after the mandate narrows.

        `self.clauses[i]` is already a plain `str`: `StrDesc.get` decodes the
        slot bytes and hands back an ordinary Python value, not a storage view.
        `gl.storage.copy_to_memory` is for storage-backed composites -- it reads
        `__type_desc__` off its argument and asserts it is present -- so calling
        it on a primitive raises `AssertionError`, which is not a
        `gl.vm.UserError` and escapes as an unclassified VM fault.
        """
        out: list[tuple[int, str]] = []
        for i in range(len(self.clauses)):
            if self.revoked[i]:
                continue
            out.append((i, self.clauses[i]))
        return out

    def _approved_newest_first(self):
        """(timestamp, amount) for approved spends, newest first, read lazily.

        A generator rather than a list so `period_spent_newest_first` stops the
        moment it reaches a spend older than the window. Each `self.spends[i]`
        is a storage read, so materializing the full history would make every
        request pay for records the window is about to discard.
        """
        for i in range(len(self.spends) - 1, -1, -1):
            s = self.spends[i]
            if s.outcome != APPROVED:
                continue
            yield (int(s.at), int(s.amount))

    def _spent_in_period(self) -> int:
        return period_spent_newest_first(
            self._approved_newest_first(), self._now(), int(self.period_seconds)
        )

    def _now(self) -> int:
        """Consensus block time in whole seconds.

        Parsing lives in `mandate_core.parse_block_time` so the timezone rule it
        enforces is unit-testable without a runtime.

        A `ValueError` from the parser would escape as an unclassified VM error,
        which validators cannot compare. Every node sees the same block time, so
        a malformed one fails identically everywhere: `[EXPECTED]`, carrying the
        offending value so the two messages match on substance.

        The range check exists for the same reason: `_commit` writes this into a
        `u256` field, and a pre-epoch or absurd timestamp would fault inside
        `u256()` rather than raise something a validator can compare.
        """
        try:
            now = parse_block_time(gl.message_raw["datetime"])
        except ValueError as e:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bad block time: {e}") from None
        if not 0 <= now <= U256_MAX:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bad block time: out of range {now}")
        return now

    def _listed(self, table: TreeMap[str, bool], payee: Address) -> bool:
        """Membership by keyed lookup, not by scanning the table.

        The key must be built exactly as the setters build it, or a listed payee
        silently reads as unlisted -- which for the denylist would be a bypass.
        """
        return bool(table.get(normalize_address(payee.as_hex)))

    # --- reads ---

    @gl.public.view
    def mandate(self) -> dict:
        """The mandate as audited: clause ids, text, and a content address."""
        active = self._active_clauses()
        return {
            "clauses": [{"id": i, "text": t} for i, t in active],
            "digest": mandate_digest([t for _, t in active]),
            "revoked_ids": [i for i in range(len(self.revoked)) if self.revoked[i]],
        }

    @gl.public.view
    def limits(self) -> dict:
        lim = self._limits()
        return {
            "per_tx_cap": lim.per_tx_cap,
            "period_cap": lim.period_cap,
            "period_seconds": lim.period_seconds,
            "auto_approve_under": lim.auto_approve_under,
            "min_confidence": lim.min_confidence,
            "confidence_tol": lim.confidence_tol,
        }

    @gl.public.view
    def spent_in_period(self) -> int:
        return self._spent_in_period()

    @gl.public.view
    def remaining_in_period(self) -> int:
        return max(0, int(self.period_cap) - self._spent_in_period())

    @gl.public.view
    def total_spends(self) -> int:
        return len(self.spends)

    @gl.public.view
    def get_spend(self, spend_id: int) -> dict:
        spend_id = _require_int(spend_id, "spend_id")
        if spend_id < 0 or spend_id >= len(self.spends):
            raise gl.vm.UserError(f"{ERROR_EXPECTED} no such spend")
        s = self.spends[spend_id]
        return {
            "id": spend_id,
            "requester": s.requester.as_hex,
            "payee": s.payee.as_hex,
            "amount": int(s.amount),
            "memo": s.memo,
            "outcome": s.outcome,
            "reason": s.reason,
            "clause_id": int(s.clause_id) if s.cited else None,
            "confidence": int(s.confidence),
            "at": int(s.at),
        }

    @gl.public.view
    def simulate(self, payee: str, amount: int) -> dict:
        """Deterministic screening without spending anything.

        Free and LLM-free, so an agent can check whether a spend would clear the
        numbers before committing gas. It cannot predict the clause decision --
        that needs a model -- so an ESCALATE outcome means "the numbers are fine,
        the purpose still has to hold up".
        """
        # Guarded exactly as the write path guards it, so a simulation answers
        # the question the caller is actually about to ask. A view that accepted
        # `"500"` while `request_spend("...", "500", ...)` refused it would be
        # worse than no simulation at all.
        amount = _require_u256(amount, "amount")
        payee_addr = _parse_address(payee, "payee")
        screen = screen_request(
            amount=amount,
            payee_denylisted=self._listed(self.denylist, payee_addr),
            payee_allowlisted=self._listed(self.allowlist, payee_addr),
            spent_in_period=self._spent_in_period(),
            clause_count=len(self._active_clauses()),
            limits=self._limits(),
        )
        return {
            "outcome": screen.outcome,
            "reason": screen.reason,
            "needs_review": not screen.is_settled(),
        }

    # --- owner controls ---

    def _require_owner(self) -> None:
        if gl.message.sender_address != self.owner:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} owner only")

    @gl.public.write
    def add_clause(self, text: str) -> int:
        """Widen the mandate. Owner only -- this is the one operation an agent
        must never reach, or it can talk its way into a broader mandate and the
        whole arrangement is theater."""
        self._require_owner()
        if not isinstance(text, str) or not text.strip():
            raise gl.vm.UserError(f"{ERROR_EXPECTED} clause text must be non-empty")
        if len(text) > MAX_CLAUSE_CHARS:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} clause too long")
        self.clauses.append(text)
        self.revoked.append(False)
        return len(self.clauses) - 1

    @gl.public.write
    def revoke_clause(self, clause_id: int) -> None:
        """Narrow the mandate. Ids are never reused, so audit trails survive."""
        self._require_owner()
        clause_id = _require_int(clause_id, "clause_id")
        if clause_id < 0 or clause_id >= len(self.clauses):
            raise gl.vm.UserError(f"{ERROR_EXPECTED} no such clause")
        self.revoked[clause_id] = True

    @gl.public.write
    def set_agent(self, agent: str, allowed: bool) -> None:
        self._require_owner()
        allowed = _require_bool(allowed, "allowed")
        self.agents[normalize_address(_parse_address(agent, "agent").as_hex)] = allowed

    @gl.public.write
    def set_allowlist(self, payee: str, allowed: bool) -> None:
        self._require_owner()
        allowed = _require_bool(allowed, "allowed")
        self.allowlist[normalize_address(_parse_address(payee, "payee").as_hex)] = allowed

    @gl.public.write
    def set_denylist(self, payee: str, blocked: bool) -> None:
        self._require_owner()
        blocked = _require_bool(blocked, "blocked")
        self.denylist[normalize_address(_parse_address(payee, "payee").as_hex)] = blocked

    # --- write path ---

    @gl.public.write
    def request_spend(self, payee: str, amount: int, memo: str) -> dict:
        """Adjudicate one spend against the mandate.

        Ordering is the whole design: deterministic screening runs first and
        settles the common case, and the consensus round happens only for a
        request whose numbers already cleared.
        """
        sender = normalize_address(gl.message.sender_address.as_hex)
        if sender != normalize_address(self.owner.as_hex):
            if not self.agents.get(sender):
                raise gl.vm.UserError(f"{ERROR_EXPECTED} sender is not an authorized agent")

        if not isinstance(memo, str):
            raise gl.vm.UserError(f"{ERROR_EXPECTED} memo must be a string")
        if len(memo) > MAX_MEMO_CHARS:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} memo too long")
        # Calldata decodes integers at arbitrary precision, but `_commit` writes
        # the amount into a `u256` field even when the request is refused, so
        # the audit record stays truthful. An amount too wide to store is
        # rejected here rather than left to fault inside `u256()`, where it
        # would surface as an unclassified error instead of a comparable one.
        #
        # A negative or zero amount deliberately survives this guard: it is
        # representable, so it is recorded as a denial reasoned
        # `amount_not_positive` rather than raised. That distinction -- refuse
        # what cannot be represented, record what can -- is the line the whole
        # boundary is drawn on.
        amount = _require_u256(amount, "amount")
        payee_addr = _parse_address(payee, "payee")

        active = self._active_clauses()
        screen = screen_request(
            amount=amount,
            payee_denylisted=self._listed(self.denylist, payee_addr),
            payee_allowlisted=self._listed(self.allowlist, payee_addr),
            spent_in_period=self._spent_in_period(),
            clause_count=len(active),
            limits=self._limits(),
        )

        verdict = dict(DENY_VERDICT)
        if not screen.is_settled():
            verdict = self._clause_verdict(payee_addr, amount, memo, active)

        return self._commit(payee_addr, amount, memo, screen, verdict)

    def _clause_verdict(
        self,
        payee: Address,
        amount: int,
        memo: str,
        active: list[tuple[int, str]],
    ) -> dict:
        """One consensus round covering the clause decision.

        Storage is materialized into plain values *before* the nondet block:
        storage handles are unusable inside it. Everything the prompt is built
        from is deterministic across nodes, so leader and validators construct
        byte-identical prompts.
        """
        limits = self._limits()
        clause_ids = [i for i, _ in active]
        clause_texts = [t for _, t in active]
        allowed = frozenset(clause_ids)

        salt = request_salt(
            mandate=mandate_digest(clause_texts),
            payee=payee.as_hex,
            amount=amount,
            memo=memo,
        )
        label = payee.as_hex

        def leader_fn() -> str:
            return encode_verdict(
                _review(
                    salt=salt,
                    clause_ids=clause_ids,
                    clause_texts=clause_texts,
                    payee_label=label,
                    memo=memo,
                    allowed=allowed,
                    limits=limits,
                )
            )

        def validator_fn(leader_res: gl.vm.Result) -> bool:
            if isinstance(leader_res, gl.vm.UserError):
                # The leader raised. Re-run to see whether this node fails the
                # same way; a validator that succeeds where the leader failed
                # must disagree rather than ratify the failure.
                try:
                    leader_fn()
                except gl.vm.UserError as mine:
                    return errors_agree(leader_res.message, mine.message)
                except Exception:
                    return False
                return False
            if not isinstance(leader_res, gl.vm.Return):
                # `VMError` (OOM, exit code) carries no classified message, so
                # there is nothing to compare on. Disagree and force rotation.
                return False
            # Decode the leader's calldata into the verdict it claims, accepting
            # it only in canonical form. This is the same coercion the agreed
            # result passes through on its way to storage, so requiring a fixed
            # point of it is what makes "the validator agreed" and "this is what
            # gets written" the same statement.
            #
            # Comparing the reported numbers directly is what got a previous
            # revision rejected: `confidence` was compared before the
            # `min_confidence` threshold, so with a minimum of 75 and a
            # tolerance of 20 a leader reporting 74 and a leader reporting 94
            # both validated against an independently computed 94 -- and then
            # stored a denial and an approval respectively.
            #
            # It also subsumes every shape check that used to stand here: key
            # set, decision vocabulary, and a bool `clause_id` posing as clause
            # 1 all fail the fixed-point test, because `canonicalize_verdict`
            # rejects each of them and its output is not what came in.
            theirs = canonical_leader_verdict(leader_res.calldata, allowed, limits)
            if theirs is None:
                return False
            # Re-do the work independently. Shape-checking the leader's answer
            # would validate formatting, not correctness.
            mine = _review(
                salt=salt,
                clause_ids=clause_ids,
                clause_texts=clause_texts,
                payee_label=label,
                memo=memo,
                allowed=allowed,
                limits=limits,
            )
            return verdicts_agree(mine, theirs, limits)

        # `run_nondet_unsafe` is declared `-> Lazy[T]` but carries the SDK's
        # `@_lazy_api` decorator, whose eager wrapper calls `.get()`. The call
        # therefore returns the consensus-agreed value directly, not a Lazy.
        result = gl.vm.run_nondet_unsafe(leader_fn, validator_fn)
        return canonicalize_verdict(result, allowed, limits)

    def _commit(
        self,
        payee: Address,
        amount: int,
        memo: str,
        screen: Screen,
        verdict: dict,
    ) -> dict:
        """Post-consensus state mutation. The only place storage is written."""
        outcome, reason, clause_id, confidence = settle(screen, verdict)

        spend_id = len(self.spends)
        self.spends.append(
            Spend(
                requester=gl.message.sender_address,
                payee=payee,
                amount=u256(amount if amount > 0 else 0),
                memo=memo,
                outcome=outcome,
                reason=reason,
                clause_id=u256(clause_id if clause_id is not None else 0),
                cited=clause_id is not None,
                confidence=u256(confidence),
                at=u256(self._now()),
            )
        )
        return {
            "id": spend_id,
            "outcome": outcome,
            "reason": reason,
            "clause_id": clause_id,
            "confidence": confidence,
        }


def _review(
    *,
    salt: str,
    clause_ids: list[int],
    clause_texts: list[str],
    payee_label: str,
    memo: str,
    allowed: frozenset[int],
    limits: Limits,
) -> dict:
    """Ask the model whether the purpose fits a clause; canonicalize the answer.

    Runs inside the nondet block on both leader and validators, so it must be
    free of storage access and nested nondet calls. `gl.eq_principle.*` helpers
    are deliberately not used here - they open their own nondet block, and
    nesting is rejected by genvm-lint.
    """
    prompt = build_review_prompt(
        salt=salt,
        clause_ids=clause_ids,
        clauses=clause_texts,
        payee_label=payee_label,
        memo=memo,
    )
    raw = gl.nondet.exec_prompt(prompt, response_format="json")
    return canonicalize_verdict(raw, allowed, limits)
